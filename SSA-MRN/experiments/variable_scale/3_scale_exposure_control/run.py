def _decode_sources(payload, expected, payload_sha256, bundle_hash):
    import base64, hashlib, json, zlib
    try:
        packed = base64.b64decode("".join(payload.split()), validate=True)
        if hashlib.sha256(packed).hexdigest() != payload_sha256:
            raise ValueError("Packed payload hash mismatch")
        sources = json.loads(zlib.decompress(packed).decode("utf-8"))
        if set(sources) != set(expected):
            raise ValueError("Embedded file list mismatch")
        if hashlib.sha256(json.dumps(expected, sort_keys=True).encode()).hexdigest() != bundle_hash:
            raise ValueError("Embedded hash manifest mismatch")
        for name, source in sources.items():
            if not isinstance(source, str) or hashlib.sha256(source.encode()).hexdigest() != expected[name]:
                raise ValueError("Embedded source checksum failed: " + name)
            if name.endswith(".py"):
                compile(source, name, "exec")
        return sources
    except Exception as error:
        raise ValueError("Cell bundle is incomplete or modified. Replace the ENTIRE cell, "
                         "or import run.ipynb. Do not disable checksums. " + str(error)) from error

