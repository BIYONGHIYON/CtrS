def conjugate(x):return np.concatenate((x[...,:1],-x[...,1:]),axis=-1)
def onion_reference(a,b):
    n=a.shape[-1]
    if n==1:return a*b
    h=n//2;x,y=a[...,:h],conjugate(a[...,h:]);z,w=b[...,:h],conjugate(b[...,h:])
    if n==2:return np.concatenate((x*z-w*y,x*w+z*y),axis=-1)
    return np.concatenate((onion_reference(x,z)-onion_reference(w,conjugate(y)),onion_reference(conjugate(x),w)+onion_reference(z,y)),axis=-1)

def q2n_reference(ref,pred,block=32):
    c,h,w=ref.shape
    def blocks(x):
        x=np.floor(np.clip(x,0,65535)+.5).transpose(1,2,0)
        return x.reshape(h//block,block,w//block,block,c).transpose(0,2,1,3,4).reshape(-1,block,block,c)
    a,b=blocks(ref),blocks(pred);mean=a.mean((1,2),keepdims=True);std=a.std((1,2),ddof=1,keepdims=True);std=np.where(std==0,np.finfo(float).eps,std)
    a=(a-mean)/std+1;b=np.where(mean==0,b+1,(b-mean)/std+1);b=conjugate(b)
    m1,m2=a.mean((1,2)),b.mean((1,2));sq1=np.sum(m1*m1,axis=-1);sq2=np.sum(m2*m2,axis=-1)
    bias=2*np.sqrt(sq1)*np.sqrt(sq2)/(sq1+sq2);factor=block*block/(block*block-1)
    var=factor*np.mean(np.sum(a*a,axis=-1),axis=(1,2))+factor*np.mean(np.sum(b*b,axis=-1),axis=(1,2))-factor*(sq1+sq2)
    q=np.zeros_like(m1);nonzero=var!=0;q[~nonzero,-1]=bias[~nonzero]
    q[nonzero]=(factor*onion_reference(a[nonzero],b[nonzero]).mean((1,2))-factor*onion_reference(m1[nonzero],m2[nonzero]))*(bias[nonzero]*2/var[nonzero])[:,None]
    return float(np.linalg.norm(q,axis=-1).mean())

def fr_with_matlab_resize(pred,lms,ms,pan,weights):
    # Matrix generated by actual MATLAB imresize on double identity inputs.
    pan=np.asarray(pan).squeeze();filtered=current._interp23tap(weights@pan@weights.T,4);c=pred.shape[0]
    dl=float(np.mean([abs(current._block_uqi(pred[i],pred[j])-current._block_uqi(lms[i],lms[j])) for i in range(c) for j in range(i+1,c)]))
    ds=float(np.mean([abs(current._block_uqi(pred[i],pan)-current._block_uqi(lms[i],filtered)) for i in range(c)]))
    return dict(D_lambda=dl,D_s=ds,QNR=(1-dl)*(1-ds))

